import { z } from 'zod';
import { isValidDate, MONTH_RE, TIME_RE } from '../utils/dates';
import { rupeesToPaise } from '../utils/money';

export const objectId = z.string().regex(/^[a-f\d]{24}$/i, 'Invalid id');
export const dateStr = z.string().refine(isValidDate, 'Invalid date (use YYYY-MM-DD)');
export const timeStr = z.string().regex(TIME_RE, 'Invalid time (use HH:mm)');
export const monthStr = z.string().regex(MONTH_RE, 'Invalid month (use YYYY-MM)');

const MAX_RUPEES = 10_000_000;

/** Rupee amount from the client (max 2 decimals), converted to integer paise. */
export const rupeesPositive = z.coerce
  .number({ error: 'Enter a valid amount' })
  .positive('Amount must be more than ₹0')
  .max(MAX_RUPEES, 'Amount is too large')
  .refine((v) => Math.abs(rupeesToPaise(v) - v * 100) < 0.001, 'Use at most 2 decimal places')
  .transform(rupeesToPaise);

export const rupeesNonNegative = z.coerce
  .number({ error: 'Enter a valid amount' })
  .min(0, 'Amount cannot be negative')
  .max(MAX_RUPEES, 'Amount is too large')
  .refine((v) => Math.abs(rupeesToPaise(v) - v * 100) < 0.001, 'Use at most 2 decimal places')
  .transform(rupeesToPaise);

/** Unique id generated by the app for each form; repeating the same id never creates a second record. */
export const requestId = z.string().trim().min(8).max(100).optional();

export const paymentMethod = z.enum(['cash', 'upi', 'bank']);

export const shortText = (max = 300) => z.string().trim().max(max).optional().default('');

export const reasonSchema = z.object({
  reason: z.string().trim().min(3, 'Please enter a reason').max(300),
});

export const pageQuery = z.object({
  page: z.coerce.number().int().min(1).default(1),
  limit: z.coerce.number().int().min(1).max(100).default(20),
});

export const dateRangeQuery = z.object({
  from: dateStr.optional(),
  to: dateStr.optional(),
});

export function toPage(q: { page: number; limit: number }) {
  return { page: q.page, limit: q.limit, skip: (q.page - 1) * q.limit };
}

/** Parses input with a schema; throws ZodError (converted to a 400 response) on failure. */
export function parse<S extends z.ZodType>(schema: S, value: unknown): z.output<S> {
  return schema.parse(value ?? {});
}
